def nic_div(code):
    return code[:2]


def convert(companies_src, biz_src, notes, section_name, section_range):
    companies, financials, biz, bnote = {}, {}, {}, {}
    for cid, row in companies_src.items():
        if len(row) == 13:
            name, tk, bpath, rev, ebm, npm, roce, roe, nd, pe, ev, mc, flag = row
        else:
            name, tk, rev, ebm, npm, roce, roe, nd, pe, ev, mc, flag = row
            bpath = None
        path = bpath if bpath else f"quote/nse/{tk}"
        companies[cid] = {"n": name, "tk": tk, "ctry": "India", "path": path}
        ebitda = round(rev * ebm / 100, 3) if (rev is not None and ebm is not None) else None
        ni = round(rev * npm / 100, 3) if (rev is not None and npm is not None) else None
        netcash = round(-nd * ebitda, 3) if (nd is not None and ebitda) else None
        financials[cid] = {
            "cur": "INR", "rev": rev, "ebitda": ebitda, "ni": ni,
            "roce": roce, "roe": roe, "netcash": netcash, "pe": pe, "ev": ev, "mc": mc,
            "fetched_at": None, "error": None,
        }
        if flag:
            pass  # company-level flags carried via map's "flags" below
    flags = {cid: row[-1] for cid, row in companies_src.items() if row[-1]}
    for code, (ids, note) in biz_src.items():
        biz[code] = ids
        bnote[code] = note
    return companies, financials, {"name": section_name, "range": section_range, "biz": biz, "bnote": bnote, "flags": flags, "notes": notes}


def main():
    all_companies, all_financials = {}, {}
    ci, fi, mi = convert(I_COMPANIES, I_BIZ, I_NOTES, "Accommodation and food service", "55-56")
    cj, fj, mj = convert(J_COMPANIES, J_BIZ, J_NOTES, "Publishing, film and broadcasting", "58-60")
    all_companies.update(ci); all_companies.update(cj)
    all_financials.update(fi); all_financials.update(fj)

    comp_path = os.path.join(H, "data", "companies.json")
    fin_path = os.path.join(H, "data", "financials.json")
    comp = json.load(open(comp_path, encoding="utf-8"))
    fin = json.load(open(fin_path, encoding="utf-8"))
    overlap = set(comp) & set(all_companies)
    if overlap:
        raise SystemExit("id collision with existing companies.json: " + ", ".join(sorted(overlap)))
    comp.update(all_companies)
    fin.update(all_financials)
    json.dump(comp, open(comp_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1, sort_keys=True)
    json.dump(fin, open(fin_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1, sort_keys=True)
    json.dump(mi, open(os.path.join(H, "data", "map_I.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(mj, open(os.path.join(H, "data", "map_J.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"added {len(all_companies)} companies ({len(ci)} from I, {len(cj)} from J)")
    print("wrote map_I.json, map_J.json")


if __name__ == "__main__":
    main()
